const TAG = 'malmabeauty-20';

function amzLink(asin, brand, name) {
  if (asin) return `https://www.amazon.com/dp/${asin}?tag=${TAG}`;
  return `https://www.amazon.com/s?k=${encodeURIComponent(`${brand} ${name}`)}&tag=${TAG}`;
}

